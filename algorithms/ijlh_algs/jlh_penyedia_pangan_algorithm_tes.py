import os
from qgis.PyQt.QtCore import QCoreApplication
from qgis.core import (
    QgsProcessing,
    QgsFeatureSink,
    QgsProcessingAlgorithm,
    QgsProcessingParameterVectorLayer,
    QgsProcessingParameterFeatureSink,
    QgsProcessingParameterEnum,
    QgsVectorLayer
)
import processing


class JLHPenyediaPangan(QgsProcessingAlgorithm):
    """
    02. Indeks Jasa Lingkungan Hidup (IJLH) – JLH Penyedia Pangan
    """
    OUTPUT = 'OUTPUT'
    PENUTUP_LAHAN = 'PENUTUP_LAHAN'
    EKOREGION = 'EKOREGION'
    GRID = 'GRID'
    BENTUK_OUTPUT = 'BENTUK_OUTPUT'
    SKOR_JLH = 'SKOR_JLH'
    PULAU = 'PULAU'

    bentuk_output_list = ['Grid', 'Poligon']
    skor_jlh_list = ['Kabupaten/Kota', 'Nasional']  # menentukan sumber file skor
    pulau_list = ['Jawa', 'Sumatera', 'Kalimantan', 'Sulawesi', 'Bali–Nusra', 'Maluku', 'Papua']

    # Bobot matra
    BOBOT_EK = 0.28
    BOBOT_VE = 0.12
    BOBOT_LC = 0.60

    def initAlgorithm(self, config):
        self.addParameter(
            QgsProcessingParameterEnum(
                self.PULAU,
                self.tr('Pulau (pilih salah satu untuk mode "kabupaten/kota")'),
                options=self.pulau_list,
                allowMultiple=True,
                defaultValue=list(range(len(self.pulau_list)))
            )
        )
        self.addParameter(
            QgsProcessingParameterEnum(
                self.BENTUK_OUTPUT,
                self.tr('Bentuk Output'),
                options=self.bentuk_output_list,
                defaultValue=0  # Grid
            )
        )
        self.addParameter(
            QgsProcessingParameterEnum(
                self.SKOR_JLH,
                self.tr('Skor IJLH yang Digunakan'),
                options=self.skor_jlh_list,
                defaultValue=1  # Nasional
            )
        )
        self.addParameter(
            QgsProcessingParameterVectorLayer(
                self.PENUTUP_LAHAN,
                self.tr('Penutup Lahan'),
                [QgsProcessing.TypeVectorAnyGeometry]
            )
        )
        self.addParameter(
            QgsProcessingParameterVectorLayer(
                self.EKOREGION,
                self.tr('Ekoregion'),
                [QgsProcessing.TypeVectorAnyGeometry]
            )
        )
        self.addParameter(
            QgsProcessingParameterVectorLayer(
                self.GRID,
                self.tr('Grid (opsional; wajib bila output Grid)'),
                [QgsProcessing.TypeVectorAnyGeometry],
                optional=True
            )
        )
        self.addParameter(
            QgsProcessingParameterFeatureSink(
                self.OUTPUT,
                self.tr('JLH Penyedia Pangan')
            )
        )

    def processAlgorithm(self, parameters, context, feedback):
        # Inputs
        pl = parameters[self.PENUTUP_LAHAN]
        ekoregion = parameters[self.EKOREGION]
        grid = parameters[self.GRID]

        bentuk_output = self.bentuk_output_list[self.parameterAsEnum(parameters, self.BENTUK_OUTPUT, context)]
        skor_jlh = self.skor_jlh_list[self.parameterAsEnum(parameters, self.SKOR_JLH, context)]
        pulau_idx_list = self.parameterAsEnums(parameters, self.PULAU, context)
        selected_islands = [self.pulau_list[i] for i in pulau_idx_list] if pulau_idx_list else self.pulau_list
        # Validasi pilihan pulau untuk mode Kabupaten/Kota
        if skor_jlh == 'Kabupaten/Kota':
            # pulau_idx_list adalah list index yang dipilih pada parameter Pulau
            if pulau_idx_list is None or len(pulau_idx_list) != 1:
                raise Exception(self.tr(
                    'Untuk mode "Kabupaten/Kota", Anda harus memilih tepat 1 pulau pada parameter "Pulau".'
                ))

        # Paths
        this_file = os.path.abspath(__file__)
        plugin_root = os.path.dirname(os.path.dirname(os.path.dirname(this_file)))
        data_root = os.path.join(plugin_root, "data", "jlh_pgn")
        data_root_kabkota = os.path.join(data_root, "kabupaten_kota")

        # Helpers
        def load_csv_table(csv_abs_path: str, name: str) -> QgsVectorLayer:
            csv_abs_path = os.path.normpath(csv_abs_path)
            for delim in (';', ','):
                uri = f"file:///{csv_abs_path}?encoding=UTF-8&delimiter={delim}&geomType=none"
                lyr = QgsVectorLayer(uri, name, "delimitedtext")
                if lyr.isValid():
                    return lyr
            raise Exception(self.tr(f'CSV tidak valid atau tidak ditemukan:\n{csv_abs_path}'))

        def pl_filename(island_name: str) -> str:
            base = {
                'Jawa': 'skor_pl_pgn_jawa.csv',
                'Sumatera': 'skor_pl_pgn_sumatera.csv',
                'Kalimantan': 'skor_pl_pgn_kalimantan.csv',
                'Sulawesi': 'skor_pl_pgn_sulawesi.csv',
                'Papua': 'skor_pl_pgn_papua.csv',
                'Bali–Nusra': 'skor_pl_pgn_balinusra.csv',
                'Maluku': 'skor_pl_pgn_maluku.csv',
            }
            if island_name not in base:
                raise Exception(self.tr(f"Pulau tidak dikenal: {island_name}"))
            return base[island_name]

        def has_field(layer: QgsVectorLayer, name: str) -> bool:
            return layer.fields().indexFromName(name) != -1

        # 1) Intersection PL × Ekoregion (bawa LC, KBA_250, KVA_250)
        inter = processing.run(
            "qgis:intersection",
            {
                'INPUT': pl,
                'OVERLAY': ekoregion,
                'INPUT_FIELDS': ['LC'],
                'OVERLAY_FIELDS': ['KBA_250', 'KVA_250'],
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 2) Join KBA
        kba_csv = os.path.join(data_root, 'skor_kba_pgn.csv')
        kba_layer = load_csv_table(kba_csv, 'skor_kba_pgn')
        src_kba = processing.run(
            "qgis:joinattributestable",
            {
                'INPUT': inter,
                'FIELD': 'KBA_250',
                'INPUT_2': kba_layer,
                'FIELD_2': 'EKOREGION',
                'FIELDS_TO_COPY': ['S_EK'],
                'METHOD': 0,
                'DISCARD_NONMATCHING': False,
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 3) Join KVA
        kva_csv = os.path.join(data_root, 'skor_kva_pgn.csv')
        kva_layer = load_csv_table(kva_csv, 'skor_kva_pgn')
        src_kva = processing.run(
            "qgis:joinattributestable",
            {
                'INPUT': src_kba,
                'FIELD': 'KVA_250',
                'INPUT_2': kva_layer,
                'FIELD_2': 'VEGETASI',
                'FIELDS_TO_COPY': ['S_VE'],
                'METHOD': 0,
                'DISCARD_NONMATCHING': False,
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 4) Join PL (Nasional: FIELD_2='LC'; Kab/Kota: FIELD_2='PL_KABKOTA', skor= S_PL_KABKOTA -> dinormalkan ke 'S_LC')
        def join_skor_pl(source_layer):
            current = source_layer
            for isl in selected_islands:
                if skor_jlh == 'Kabupaten/Kota':
                    csv_path = os.path.join(data_root_kabkota, pl_filename(isl))
                    name = f'skor_pl_kabkota_{isl}'
                    field2 = 'PL_KABKOTA'
                    score_field = 'S_PL_KABKOTA'
                else:
                    csv_path = os.path.join(data_root, pl_filename(isl))
                    name = f'skor_pl_nasional_{isl}'
                    field2 = 'LC'
                    score_field = 'S_LC'

                pl_layer = load_csv_table(csv_path, name)

                current = processing.run(
                    "qgis:joinattributestable",
                    {
                        'INPUT': current,
                        'FIELD': 'LC',          # field pada layer sumber
                        'INPUT_2': pl_layer,
                        'FIELD_2': field2,      # field pada CSV (PL_KABKOTA atau LC)
                        'FIELDS_TO_COPY': [score_field],
                        'METHOD': 0,
                        'DISCARD_NONMATCHING': False,
                        'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                    },
                    context=context, feedback=feedback
                )["OUTPUT"]

                # Samakan nama skor menjadi 'S_LC' agar formula tetap konsisten
                if score_field != 'S_LC' and has_field(current, 'S_PL_KABKOTA'):
                    if has_field(current, 'S_LC'):
                        # timpa dengan yang baru jika ada
                        current = processing.run(
                            "qgis:fieldcalculator",
                            {
                                'INPUT': current,
                                'FIELD_NAME': 'S_LC',
                                'NEW_FIELD': False,
                                'FORMULA': 'coalesce("S_PL_KABKOTA","S_LC")',
                                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                            },
                            context=context, feedback=feedback
                        )["OUTPUT"]
                        current = processing.run(
                            "qgis:deletecolumn",
                            {
                                'INPUT': current,
                                'COLUMN': ['S_PL_KABKOTA'],
                                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                            },
                            context=context, feedback=feedback
                        )["OUTPUT"]
                    else:
                        current = processing.run(
                            "qgis:renametablefield",
                            {
                                'INPUT': current,
                                'FIELD': 'S_PL_KABKOTA',
                                'NEW_NAME': 'S_LC',
                                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                            },
                            context=context, feedback=feedback
                        )["OUTPUT"]

            return current

        src_pl = join_skor_pl(src_kva)

        # 5) Hitung indeks
        src_idx = processing.run(
            "qgis:fieldcalculator",
            {
                'INPUT': src_pl,
                'FIELD_NAME': 'JLH_Pangan',
                'FIELD_TYPE': 0,
                'FIELD_LENGTH': 20,
                'FIELD_PRECISION': 3,
                'NEW_FIELD': True,
                'FORMULA': f'"S_EK"*{self.BOBOT_EK} + "S_VE"*{self.BOBOT_VE} + "S_LC"*{self.BOBOT_LC}',
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 6) Bentuk output
        if bentuk_output == 'Poligon':
            out_src = src_idx
        else:
            if grid is None:
                raise Exception(self.tr('Layer GRID wajib diisi bila memilih output "Grid".'))
            inter_grid = processing.run(
                "qgis:intersection",
                {
                    'INPUT': src_idx,
                    'OVERLAY': grid,
                    'INPUT_FIELDS': [],
                    'OVERLAY_FIELDS': ['ID'],
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            area_poly = processing.run(
                "qgis:fieldcalculator",
                {
                    'INPUT': inter_grid,
                    'FIELD_NAME': 'AREA_POLY_M2',
                    'FIELD_TYPE': 0,
                    'FIELD_LENGTH': 20,
                    'FIELD_PRECISION': 3,
                    'NEW_FIELD': True,
                    'FORMULA': '$area',
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            area_by_id = processing.run(
                "qgis:statisticsbycategories",
                {
                    'INPUT': area_poly,
                    'CATEGORIES_FIELD_NAME': ['ID'],
                    'VALUES_FIELD_NAME': 'AREA_POLY_M2',
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            area_by_id_renamed = processing.run(
                "qgis:renametablefield",
                {
                    'INPUT': area_by_id,
                    'FIELD': 'sum',
                    'NEW_NAME': 'AREA_GRID_M2',
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            inter_grid_with_area = processing.run(
                "qgis:joinattributestable",
                {
                    'INPUT': area_poly,
                    'FIELD': 'ID',
                    'INPUT_2': area_by_id_renamed,
                    'FIELD_2': 'ID',
                    'FIELDS_TO_COPY': ['AREA_GRID_M2'],
                    'METHOD': 0,
                    'DISCARD_NONMATCHING': False,
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            prop = processing.run(
                "qgis:fieldcalculator",
                {
                    'INPUT': inter_grid_with_area,
                    'FIELD_NAME': 'JLH_Pangan_Proporsional',
                    'FIELD_TYPE': 0,
                    'FIELD_LENGTH': 20,
                    'FIELD_PRECISION': 3,
                    'NEW_FIELD': True,
                    'FORMULA': '"JLH_Pangan" * ("AREA_POLY_M2" / "AREA_GRID_M2")',
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            summed = processing.run(
                "qgis:statisticsbycategories",
                {
                    'INPUT': prop,
                    'CATEGORIES_FIELD_NAME': ['ID'],
                    'VALUES_FIELD_NAME': 'JLH_Pangan_Proporsional',
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            grid_join = processing.run(
                "qgis:joinattributestable",
                {
                    'INPUT': grid,
                    'FIELD': 'ID',
                    'INPUT_2': summed,
                    'FIELD_2': 'ID',
                    'FIELDS_TO_COPY': ['sum'],
                    'METHOD': 0,
                    'DISCARD_NONMATCHING': False,
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            out_src = processing.run(
                "qgis:renametablefield",
                {
                    'INPUT': grid_join,
                    'FIELD': 'sum',
                    'NEW_NAME': 'JLH_Pangan',
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]

        # 7) Pembulatan (khusus Nasional)
        if skor_jlh == 'Nasional':
            out_src = processing.run(
                "qgis:fieldcalculator",
                {
                    'INPUT': out_src,
                    'FIELD_NAME': 'JLH_Pangan',
                    'NEW_FIELD': False,
                    'FORMULA': 'round("JLH_Pangan")',
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]

        # 8) Kolom kategori
        out_src = processing.run(
            "qgis:fieldcalculator",
            {
                'INPUT': out_src,
                'FIELD_NAME': 'Kategori_JLH',
                'FIELD_TYPE': 2,        # String
                'FIELD_LENGTH': 20,
                'NEW_FIELD': True,
                'FORMULA': """
                CASE
                    WHEN "JLH_Pangan" >= 1.0 AND "JLH_Pangan" <= 1.8 THEN 'Sangat Rendah'
                    WHEN "JLH_Pangan" > 1.8 AND "JLH_Pangan" <= 2.6 THEN 'Rendah'
                    WHEN "JLH_Pangan" > 2.6 AND "JLH_Pangan" <= 3.4 THEN 'Sedang'
                    WHEN "JLH_Pangan" > 3.4 AND "JLH_Pangan" <= 4.2 THEN 'Tinggi'
                    WHEN "JLH_Pangan" > 4.2 AND "JLH_Pangan" <= 5.0 THEN 'Sangat Tinggi'
                    ELSE 'Tidak Diketahui'
                END
                """,
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # Output sink
        (sink, dest_id) = self.parameterAsSink(
            parameters, self.OUTPUT, context,
            out_src.fields(), out_src.wkbType(), out_src.sourceCrs()
        )

        total = 100.0 / out_src.featureCount() if out_src.featureCount() else 0
        for current, feat in enumerate(out_src.getFeatures()):
            if feedback.isCanceled():
                break
            sink.addFeature(feat, QgsFeatureSink.FastInsert)
            feedback.setProgress(int(current * total))

        return {self.OUTPUT: dest_id}

    # Metadata
    def name(self):
        return 'JLH Penyedia Pangan'

    def displayName(self):
        return self.tr(self.name())

    def group(self):
        return self.tr(self.groupId())

    def groupId(self):
        return '02. Indeks Jasa Lingkungan Hidup (IJLH)'

    def tr(self, string):
        return QCoreApplication.translate('Processing', string)

    def createInstance(self):
        return JLHPenyediaPangan()
