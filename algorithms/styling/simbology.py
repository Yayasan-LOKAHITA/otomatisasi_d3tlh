    # IKP Lahan (oranye-coklat) + Tidak Dihitung (abu-abu)
    def _palette_ikp_lahan(self, layer):
        cats = [
            self._cat(layer, "Sangat Rendah", 255, 230, 200),  # #FFE6C8
            self._cat(layer, "Rendah", 255, 190, 120),  # #FFBE78
            self._cat(layer, "Sedang", 230, 135, 60),  # #E6873C
            self._cat(layer, "Tinggi", 180, 95, 30),  # #B45F1E
            self._cat(layer, "Sangat Tinggi", 120, 60, 20),  # #783C14
        ]
        # Tambah kategori "Tidak Dihitung"
        base = QgsSymbol.defaultSymbol(layer.geometryType())
        sym = base.clone()
        sym.setColor(QColor(222, 222, 222))  # ~RGB(239.27,239.27,239.27)
        self._no_outline(sym)
        cats.append(QgsRendererCategory("Tidak Dihitung", sym, "Tidak Dihitung"))
        return cats

    # IKP Udara (grays-blue)
    def _palette_ikp_udara(self, layer):
        return [
            self._cat(layer, "Sangat Rendah", 240, 245, 245),  # #F0F5F5
            self._cat(layer, "Rendah", 210, 220, 225),  # #D2DCE1
            self._cat(layer, "Sedang", 170, 180, 190),  # #AAB4BE
            self._cat(layer, "Tinggi", 120, 130, 145),  # #788291
            self._cat(layer, "Sangat Tinggi", 80, 90, 105),  # #505A69
        ]

    # Template field per tema (pakai YY)
    def _field_template(self, theme_index):
        return {
            self.THEME_JLH_KPHK_N: "KPHK_YY_KK",
            self.THEME_JLH_KPHK_KK: "KPHK_YY_KK",
            self.THEME_JLH_KPKU_N: "KPKU_YY",
            self.THEME_JLH_KPKU_KK: "KPKU_YY_KK",
            self.THEME_JLH_KPGA_N: "KPGA_YY_KK",
            self.THEME_JLH_KPGA_KK: "KPGA_YY_KK",
            self.THEME_JLH_KPYA_N: "KPYA_YY",
            self.THEME_JLH_KPYA_KK: "KPYA_YY_KK",
            self.THEME_JLH_KPGN: "KPGN_YY",
            self.THEME_JLH_KPPK: "KPPK_YY",
            self.THEME_IKP_AIR: "KIKPAIR",
            self.THEME_IKP_KEHATI: "KIKPLH",
            self.THEME_IKP_LAHAN: "KIKPLHN",
            self.THEME_IKP_UDARA: "KIKPUDR",
        }[theme_index]

    def _autodetect_field(self, layer, theme_index, year_opt):
        names = [f.name() for f in layer.fields()]
        templ = self._field_template(theme_index)

        # IKP themes: langsung pakai nama field
        if "KIKP" in templ or templ in ("KIKPLH", "KIKPLHN"):
            if templ not in names:
                raise QgsProcessingException(self.tr(f"Kolom {templ} tidak ditemukan."))
            return templ

        # JLH themes: punya placeholder YY
        if "YY" in templ:
            if year_opt is not None:
                yy = f"{int(year_opt) % 100:02d}"
                candidate = templ.replace("YY", yy)
                if candidate in names:
                    return candidate

            # fallback: cari pola yang sama dengan regex
            base = templ.replace("YY", r"(\d{2})")
            pattern = re.compile("^" + base + "$")
            candidates = [n for n in names if pattern.fullmatch(n)]
            if candidates:
                # ambil yang suffix YY paling besar
                def yy_of(n):
                    m = re.search(r"(\d{2})$", n)
                    return int(m.group(1)) if m else -1

                candidates.sort(key=yy_of, reverse=True)
                return candidates[0]

        raise QgsProcessingException(
            self.tr(f"Kolom untuk tema ini tidak ditemukan (template: {templ}).")
        )

    def _palette_for(self, theme_index, layer):
        if theme_index in (self.THEME_IKP_AIR,):
            return self._palette_ikp_air(layer)
        if theme_index in (self.THEME_IKP_KEHATI,):
            return self._palette_ikp_kehati(layer)
        if theme_index in (self.THEME_IKP_LAHAN,):
            return self._palette_ikp_lahan(layer)
        if theme_index in (self.THEME_IKP_UDARA,):
            return self._palette_ikp_udara(layer)
        # default untuk seluruh JLH
        return self._palette_jlh(layer)

    # -------------------- main -----------------------
    def processAlgorithm(self, parameters, context, feedback):
        layer = self.parameterAsLayer(parameters, self.P_LAYER, context)
        if layer is None:
            raise QgsProcessingException(self.tr("Layer tidak valid."))

        theme_index = self.parameterAsEnum(parameters, self.P_THEME, context)
        year_opt = (
            self.parameterAsInt(parameters, self.P_YEAR, context)
            if parameters.get(self.P_YEAR) is not None
            else None
        )

        field_name = (
            self.parameterAsString(parameters, self.P_FIELD, context) or ""
        ).strip()
        if not field_name:
            field_name = self._autodetect_field(layer, theme_index, year_opt)

        categories = self._palette_for(theme_index, layer)

        renderer = QgsCategorizedSymbolRenderer(field_name, categories)
        layer.setRenderer(renderer)
        layer.setName(f"{layer.name()}")
        layer.triggerRepaint()
        return {}
