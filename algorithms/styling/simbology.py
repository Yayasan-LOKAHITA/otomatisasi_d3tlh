        "JLH Penyedia Air (Kab/Kota) — KPYA_YY_KK",
        "JLH Penyedia Pangan (Nasional/Kab/Kota) — KPGN_YY",
        "JLH Penyerapan & Penyimpanan Karbon (Nasional/Kab/Kota) — KPPK_YY",
        "IKP Air — KIKPAIR",
