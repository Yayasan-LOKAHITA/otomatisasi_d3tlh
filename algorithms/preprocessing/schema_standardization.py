from qgis.PyQt.QtCore import QCoreApplication, QVariant
from qgis.core import (
    QgsProcessing, QgsFeature, QgsFeatureSink, QgsField, QgsFields,
    QgsProcessingParameterBoolean, QgsProcessingParameterField,
    QgsProcessingParameterFeatureSource, QgsProcessingParameterFeatureSink,
    QgsProcessingException, QgsProcessingAlgorithm
)

class PreprocSchemaStandardizationAlgorithm(QgsProcessingAlgorithm):
    """
    Standarisasi kolom inti tanpa dropdown jenis data.
    User cukup pilih kolom sumber mana yang ingin dipetakan.
    Kolom standar & tipe data dikunci: PL, kwshutan, KBA_250, KVA_250 (String).
    """

    # ----- parameter keys -----
    INPUT = "INPUT"
    SOURCE_FIELD_LC   = "SOURCE_FIELD_LC"        # -> LC
    SOURCE_FIELD_KWS  = "SOURCE_FIELD_KWSHUTAN"  # -> kwshutan
    SOURCE_FIELD_KBA  = "SOURCE_FIELD_KBA"       # -> KBA_250
    SOURCE_FIELD_KVA  = "SOURCE_FIELD_KVA"       # -> KVA_250
    OVERWRITE_IF_EXISTS = "OVERWRITE_IF_EXISTS"
    OUTPUT = "OUTPUT"

    # ----- constants -----
    DEFAULT_LC   = "LC"
    DEFAULT_KWS  = "kwshutan"
    DEFAULT_KBA  = "KBA_250"
    DEFAULT_KVA  = "KVA_250"
    TARGET_QVARIANT = QVariant.String

    # ----- boilerplate -----
    def tr(self, s): return QCoreApplication.translate("Processing", s)
    def createInstance(self): return PreprocSchemaStandardizationAlgorithm()
    def name(self):
        return 'Standarisasi Skema Data'

    def displayName(self):
        return self.tr(self.name())
    
    def group(self):
        return self.tr(self.groupId())

    def groupId(self):
        return 'B. Preprocessing'

    def shortHelpString(self):
        return self.tr('''\
            🇮🇩 ID == Standarisasi kolom inti (nama & tipe data DIKUNCI sesuai standar):

            • LC (Penutup Lahan (PL))  
            • kwshutan (Kawasan Hutan / Forest Area)  
            • KBA_250 (Karakteristik Bentang Alam (KBA) pada Ekoregion)  
            • KVA_250 (Karakteristik Vegetasi Alami (KVA) pada Ekoregion)  

            Cara pakai:  
            1) Pilih satu atau lebih kolom sumber.  
            2) Jalankan → layer baru dengan kolom standar dibuat.  

            ──────────────
         
            Data Schema Standardization
            
            🌍 EN == Standardize key columns (names & types are LOCKED according to the standard):

            • LC (Land Cover)  
            • kwshutan (Forest Area / State-Designated Forest Area)  
            • KBA_250 (Landform Characteristic of the Ecoregion)  
            • KVA_250 (Natural Vegetation Characteristic of the Ecoregion)  

            How to use:  
            1) Choose one or more source fields.  
            2) Run → a new layer with standardized columns is created.   
        ''')

    # ----- parameters -----
    def initAlgorithm(self, config=None):
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.INPUT, self.tr("Input layer"),
                [QgsProcessing.TypeVectorAnyGeometry]
            )
        )
        self.addParameter(
            QgsProcessingParameterField(
                self.SOURCE_FIELD_LC,
                self.tr("Source field of LC classes / jenis PL → LC"),
                parentLayerParameterName=self.INPUT,
                type=QgsProcessingParameterField.Any,
                allowMultiple=False,
                optional=True
            )
        )
        self.addParameter(
            QgsProcessingParameterField(
                self.SOURCE_FIELD_KWS,
                self.tr("Source field of Forest Area / Kawasan Hutan → kwshutan"),
                parentLayerParameterName=self.INPUT,
                type=QgsProcessingParameterField.Any,
                allowMultiple=False,
                optional=True
            )
        )
        self.addParameter(
            QgsProcessingParameterField(
                self.SOURCE_FIELD_KBA,
                self.tr("Source field of landform characteristics (KBA) → KBA_250"),
                parentLayerParameterName=self.INPUT,
                type=QgsProcessingParameterField.Any,
                allowMultiple=False,
                optional=True
            )
        )
        self.addParameter(
            QgsProcessingParameterField(
                self.SOURCE_FIELD_KVA,
                self.tr("Source field of natural vegetation characteristic (KVA) → KVA_250"),
                parentLayerParameterName=self.INPUT,
                type=QgsProcessingParameterField.Any,
                allowMultiple=False,
                optional=True
            )
        )
        self.addParameter(
            QgsProcessingParameterBoolean(
                self.OVERWRITE_IF_EXISTS,
                self.tr("If standardized field already exists, overwrite values"),
                defaultValue=True
            )
        )
        self.addParameter(
            QgsProcessingParameterFeatureSink(self.OUTPUT, self.tr("Output layer"))
        )

    # ----- helpers -----
    def _ensure_field(self, fields: QgsFields, name: str, overwrite: bool) -> int:
        idx = fields.indexFromName(name)
        if idx == -1:
            fields.append(QgsField(name, self.TARGET_QVARIANT))
            idx = fields.indexFromName(name)
        else:
            if not overwrite:
                raise QgsProcessingException(
                    self.tr(f"Field '{name}' already exists. Disable overwrite or adjust structure.")
                )
        return idx

    def _to_string(self, value):
        if value is None:
            return None
        try:
            return "" if value is None else str(value)
        except Exception:
            return None

    # ----- main -----
    def processAlgorithm(self, parameters, context, feedback):
        source = self.parameterAsSource(parameters, self.INPUT, context)
        if source is None:
            raise QgsProcessingException(self.tr("Invalid input layer."))

        src_lc  = self.parameterAsString(parameters, self.SOURCE_FIELD_LC,  context)
        src_kws = self.parameterAsString(parameters, self.SOURCE_FIELD_KWS, context)
        src_kba = self.parameterAsString(parameters, self.SOURCE_FIELD_KBA, context)
        src_kva = self.parameterAsString(parameters, self.SOURCE_FIELD_KVA, context)
        overwrite = self.parameterAsBool(parameters, self.OVERWRITE_IF_EXISTS, context)

        if not (src_lc or src_kws or src_kba or src_kva):
            raise QgsProcessingException(self.tr("Select at least one source field (LC/kwshutan/KBA_250/KVA_250)."))

        in_fields: QgsFields = source.fields()
        out_fields = QgsFields(in_fields)

        idx_lc = idx_kws = idx_kba = idx_kva = -1
        if src_lc:
            idx_lc  = self._ensure_field(out_fields, self.DEFAULT_LC, overwrite)
        if src_kws:
            idx_kws = self._ensure_field(out_fields, self.DEFAULT_KWS, overwrite)
        if src_kba:
            idx_kba = self._ensure_field(out_fields, self.DEFAULT_KBA, overwrite)
        if src_kva:
            idx_kva = self._ensure_field(out_fields, self.DEFAULT_KVA, overwrite)

        (sink, dest_id) = self.parameterAsSink(
            parameters, self.OUTPUT, context,
            out_fields, source.wkbType(), source.sourceCrs()
        )

        total = max(1, source.featureCount())
        step = 100.0 / total
        names = source.fields().names()

        for i, feat in enumerate(source.getFeatures()):
            if feedback.isCanceled():
                break

            attrs = feat.attributes()
            if len(attrs) < out_fields.count():
                attrs += [None] * (out_fields.count() - len(attrs))

            if idx_lc != -1:
                val = feat[src_lc] if (src_lc in names) else None
                attrs[idx_lc] = self._to_string(val)
            if idx_kws != -1:
                val = feat[src_kws] if (src_kws in names) else None
                attrs[idx_kws] = self._to_string(val)
            if idx_kba != -1:
                val = feat[src_kba] if (src_kba in names) else None
                attrs[idx_kba] = self._to_string(val)
            if idx_kva != -1:
                val = feat[src_kva] if (src_kva in names) else None
                attrs[idx_kva] = self._to_string(val)

            new_feat = QgsFeature(out_fields)
            new_feat.setGeometry(feat.geometry())
            new_feat.setAttributes(attrs)
            sink.addFeature(new_feat, QgsFeatureSink.FastInsert)
            feedback.setProgress(int((i + 1) * step))

        return {self.OUTPUT: dest_id}
