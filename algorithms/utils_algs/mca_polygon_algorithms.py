from qgis.PyQt.QtCore import QCoreApplication
from qgis.core import (
    QgsProcessing,
    QgsFeatureSink,
    QgsProcessingAlgorithm,
    QgsProcessingParameterFeatureSource,
    QgsProcessingParameterFeatureSink,
    QgsProcessingParameterField,
    QgsProcessingException,
)
import processing


class MCA_GRID_Poligon_Algoritm(QgsProcessingAlgorithm):
    # Parameter keys
    GRID = 'GRID'
    LAYER2 = 'LAYER2'
    LAYER2_FIELD = 'LAYER2_FIELD'
    OUTPUT = 'OUTPUT'   # satu-satunya output

    def initAlgorithm(self, config=None):
        # GRID input
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.GRID,
                self.tr('GRID (polygon, wajib punya field "id" atau "ID")'),
                [QgsProcessing.TypeVectorPolygon]
            )
        )
        # Layer polygon ke-2 (bebas)
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.LAYER2,
                self.tr('Layer 2 (polygon, kolom fleksibel)'),
                [QgsProcessing.TypeVectorPolygon]
            )
        )
        # Field yang dipakai dari Layer 2 (dropdown otomatis)
        self.addParameter(
            QgsProcessingParameterField(
                self.LAYER2_FIELD,
                self.tr('Pilih kolom dari Layer 2 untuk digabung (mis. LC)'),
                parentLayerParameterName=self.LAYER2,
                type=QgsProcessingParameterField.Any,
                allowMultiple=False
            )
        )
        # GRID final
        self.addParameter(
            QgsProcessingParameterFeatureSink(
                self.OUTPUT,
                self.tr('GRID dengan atribut dominan pada kolom yang dipilih')
            )
        )

    def processAlgorithm(self, parameters, context, feedback):
        # Ambil source & daftar field
        grid_src = self.parameterAsSource(parameters, self.GRID, context)
        lyr2_src = self.parameterAsSource(parameters, self.LAYER2, context)
        grid_fields = [f.name() for f in grid_src.fields()]
        lyr2_fields = [f.name() for f in lyr2_src.fields()]

        # Deteksi field ID pada GRID
        if 'id' in grid_fields:
            id_field = 'id'
        elif 'ID' in grid_fields:
            id_field = 'ID'
        else:
            raise QgsProcessingException(
                self.tr('Field ID tidak ditemukan di GRID. Harus ada "id" atau "ID".')
            )

        # Field yang dipilih user dari Layer 2 → ini juga jadi nama kolom output
        src_field = self.parameterAsString(parameters, self.LAYER2_FIELD, context)
        if not src_field or src_field not in lyr2_fields:
            raise QgsProcessingException(self.tr('Kolom yang dipilih tidak ada di Layer 2.'))
        out_field = src_field  # nama kolom output mengikuti kolom terpilih

        grid = parameters[self.GRID]
        lyr2 = parameters[self.LAYER2]

        # 1) Intersect GRID × Layer2 (bawa ID dari GRID & src_field dari Layer2)
        inter1 = processing.run(
            "qgis:intersection",
            {
                'INPUT': grid,
                'OVERLAY': lyr2,
                'INPUT_FIELDS': [id_field],
                'OVERLAY_FIELDS': [src_field],
                'OVERLAY_FIELDS_PREFIX': '',
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 2) Dissolve by ID + src_field (akumulasi luas tiap kombinasi)
        dissolved = processing.run(
            "qgis:dissolve",
            {
                'INPUT': inter1,
                'FIELD': [id_field, src_field],
                'SEPARATE_DISJOINT': False,
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 3) Hitung luas (m2) → lglcha
        with_area = processing.run(
            "qgis:fieldcalculator",
            {
                'INPUT': dissolved,
                'FIELD_NAME': 'lglcha',
                'FIELD_TYPE': 0,  # Float
                'FIELD_LENGTH': 20,
                'FIELD_PRECISION': 3,
                'NEW_FIELD': True,
                'FORMULA': '$area',
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 4) Max(lglcha) per ID
        stats = processing.run(
            "qgis:statisticsbycategories",
            {
                'INPUT': with_area,
                'CATEGORIES_FIELD_NAME': [id_field],
                'VALUES_FIELD_NAME': 'lglcha',
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # Rename 'max' → 'lglcha_max'
        stats_renamed = processing.run(
            "qgis:renametablefield",
            {
                'INPUT': stats,
                'FIELD': 'max',
                'NEW_NAME': 'lglcha_max',
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 5) Join lglcha_max ke with_area (by ID)
        diss_join = processing.run(
            "qgis:joinattributestable",
            {
                'INPUT': with_area,
                'FIELD': id_field,
                'INPUT_2': stats_renamed,
                'FIELD_2': id_field,
                'FIELDS_TO_COPY': ['lglcha_max'],
                'METHOD': 0,
                'DISCARD_NONMATCHING': False,
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 6) Ambil pemenang (lglcha == lglcha_max), drop geometry → tabel MCA (id, src_field)
        winners = processing.run(
            "qgis:extractbyexpression",
            {
                'INPUT': diss_join,
                'EXPRESSION': "\"lglcha\" = \"lglcha_max\"",
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        mca_table = processing.run(
            "qgis:dropgeometries",
            {
                'INPUT': winners,
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # 7) Jika kolom dengan nama yang sama sudah ada di GRID → hapus dulu; kalau tidak ada, lanjut.
        if out_field in grid_fields:
            grid_no_out = processing.run(
                "qgis:deletecolumn",
                {
                    'INPUT': grid,
                    'COLUMN': [out_field],
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
            before_names = [f.name() for f in grid_no_out.fields()]
        else:
            grid_no_out = grid
            before_names = grid_fields[:]   # pakai daftar field awal

        # 8) Join kolom pilihan (src_field) dari mca ke GRID
        grid_joined = processing.run(
            "qgis:joinattributestable",
            {
                'INPUT': grid_no_out,
                'FIELD': id_field,
                'INPUT_2': mca_table,
                'FIELD_2': id_field,
                'FIELDS_TO_COPY': [src_field],
                'METHOD': 0,
                'DISCARD_NONMATCHING': False,
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            },
            context=context, feedback=feedback
        )["OUTPUT"]

        # Deteksi nama kolom hasil join (antisipasi suffix _2)
        after_names = [f.name() for f in grid_joined.fields()]
        added = [n for n in after_names if n not in before_names]
        joined_name = added[0] if added else src_field

        # 9) Rename ke nama output yang diinginkan (harus sama dengan src_field)
        if joined_name != out_field:
            grid_final = processing.run(
                "qgis:renametablefield",
                {
                    'INPUT': grid_joined,
                    'FIELD': joined_name,
                    'NEW_NAME': out_field,
                    'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
                },
                context=context, feedback=feedback
            )["OUTPUT"]
        else:
            grid_final = grid_joined

        # 10) Simpan output tunggal: GRID final
        (sink_grid, out_grid_id) = self.parameterAsSink(
            parameters, self.OUTPUT, context,
            grid_final.fields(), grid_final.wkbType(), grid_final.sourceCrs()
        )
        for f in grid_final.getFeatures():
            sink_grid.addFeature(f, QgsFeatureSink.FastInsert)

        for current, feature in enumerate(grid_final.getFeatures()):
            # Stop the algorithm if cancel button has been clicked
            if feedback.isCanceled():
                break

            # Add a feature in the sink
            sink_grid.addFeature(feature, QgsFeatureSink.FastInsert)

        return { self.OUTPUT: out_grid_id }

    # ---- Boilerplate ----
    def name(self):
        return 'mca_grid'

    def displayName(self):
        return self.tr('Maximum Combined Area (MCA) / Atribut Dominan Per Grid')

    def group(self):
        return self.tr(self.groupId())

    def groupId(self):
        return '00. Utilities'

    def tr(self, s):
        return QCoreApplication.translate('Processing', s)

    def createInstance(self):
        return MCA_GRID_Poligon_Algoritm()
