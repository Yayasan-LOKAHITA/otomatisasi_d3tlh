    def processAlgorithm(self, parameters, context, feedback):
        extent = self.parameterAsExtent(parameters, self.P_EXTENT, context)
        size_idx = self.parameterAsEnum(parameters, self.P_GRID_SIZE, context)
        crs = self.parameterAsCrs(parameters, self.P_CRS, context)
        if not crs.isValid():
            crs = QgsCoordinateReferenceSystem("EPSG:4326")

        label, d_lat, d_lon = self.GRID_CHOICES[size_idx]

        # snap extent ke grid origin
        def snap_down(v, origin, step):
            return origin + math.floor((v - origin) / step) * step

        xmin = snap_down(extent.xMinimum(), ORI_LON_MIN, d_lon)
        ymin = snap_down(extent.yMinimum(), ORI_LAT_MIN, d_lat)
        xmax = extent.xMaximum()
        ymax = extent.yMaximum()

        fields = QgsFields()
        fields.append(QgsField("ID", QVariant.String))     # nama grid
        fields.append(QgsField("Label", QVariant.String))

        sink, dest_id = self.parameterAsSink(
            parameters, self.P_OUT, context, fields, QgsWkbTypes.Polygon, crs
        )
        if sink is None:
            raise QgsProcessingException(self.tr("Tidak dapat membuat output sink."))

        # progress
        total_cols = int((xmax - xmin) / d_lon) + 2
        total_rows = int((ymax - ymin) / d_lat) + 2
        n_total = total_cols * total_rows
        n = 0

        y = ymin
        while y < ymax + 1e-12:
            x = xmin
            while x < xmax + 1e-12:
                col = int((x - ORI_LON_MIN) / d_lon)   # info tambahan
                row = int((y - ORI_LAT_MIN) / d_lat)

                # geometri
                poly = QgsGeometry.fromPolygonXY([[
                    QgsPointXY(x, y),
                    QgsPointXY(x + d_lon, y),
                    QgsPointXY(x + d_lon, y + d_lat),
                    QgsPointXY(x, y + d_lat),
                    QgsPointXY(x, y),
                ]])

                # pusat sel (untuk ID hierarkis)
                cx = x + d_lon/2.0
                cy = y + d_lat/2.0
                grid_id = self._make_hier_id(cx, cy, d_lat, d_lon)

                f = QgsFeature(fields)
                f.setGeometry(poly)
                f["ID"] = grid_id
                f["Label"] = label
                sink.addFeature(f, QgsFeatureSink.FastInsert)

                n += 1
                if n_total and n % 100 == 0:
                    feedback.setProgress(100.0 * n / n_total)
                x += d_lon
            y += d_lat

        return {self.P_OUT: dest_id}
